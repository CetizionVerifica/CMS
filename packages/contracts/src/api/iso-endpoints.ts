/**
 * The ISO add-on's endpoints (docs/iso/model.md §10, docs/contracts/endpoints.md §10), all M16's and all under
 * `/clients/{clientId}/iso/`. Every one needs `isoManagement` on the account: without it, 403 FEATURE_NOT_ENABLED after
 * the session check and before the role check, reads included; with it, 409 FEATURE_NOT_READY until the account's
 * catalogue copy is recorded. `can()` actions and roles follow docs/iso/plan.md §3.2: `own` is the person named in that
 * role on the record (M16 builds each `Resource` per action), and AP and OW see only their units (plan §3.3).
 */

const READERS = 'FA CO CA AP OW VI';
/** Set-up and record work: account admin, consultant and client admin. */
const MANAGERS = 'FA CO CA';
/** Managers, and an owner on records that name them as owner. */
const OWNER_WRITERS = 'FA CO CA OW:own';
const LIST_NOTE = 'AP/OW limited to their units (plan §3.3).';

const ROOT = '/clients/{clientId}/iso';

function isoEndpoint<const I extends Omit<EndpointInput, 'module' | 'feature'>>(input: I) {
  return endpoint({ ...input, module: 'M16', feature: 'isoManagement' } as const);
}

