import { writeFile } from 'node:fs/promises';
import { masterFromPlan } from '../from-register.js';
import { MASTER_VERSION } from '../master-data.js';
import { SAMPLE_ACT_NAMES, SAMPLE_TITLES, sampleRegisterPlan } from './register.js';

/**
 * Rewrites `master-data.ts` from the anonymised sample register (ADR M6-0002). Run from apps/api, then format:
 *   pnpm exec tsx src/modules/library/testing/write-master.ts && pnpm exec prettier --write src/modules/library/master-data.ts
 * Bump MASTER_VERSION in the written file by hand when the content changes.
 */
const library = masterFromPlan(await sampleRegisterPlan(), MASTER_VERSION, {
  actNames: SAMPLE_ACT_NAMES,
  titles: SAMPLE_TITLES,
});
const content = {
  categories: library.categories,
  acts: library.acts,
  obligations: library.obligations,
};
const out = new URL('../master-data.ts', import.meta.url);
await writeFile(
  out,
  `// Generated by testing/write-master.ts from the anonymised sample register (ADR M6-0002). Do not edit by hand.
import type { MasterLibrary } from './master.js';

export const MASTER_VERSION = ${MASTER_VERSION};

export const MASTER_CONTENT: Omit<MasterLibrary, 'version'> = ${JSON.stringify(content, null, 2)};
`,
);
console.log(
  `master library v${library.version}: ${library.acts.length} Acts, ${library.categories.length} categories, ${library.obligations.length} obligations`,
);
